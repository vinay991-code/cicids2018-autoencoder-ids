"""Score captures of ordinary traffic with the saved models and report how much each model flags.

  python tools/ordinary_traffic_check.py capture1.pcap capture2.pcap --json results/ordinary_traffic_check.json

Purpose: ordinary web, DNS and ping traffic from a normal computer contains very little that is malicious, so a model that flags a large share of it
produces false alarms on such a network. This is a check of false alarms on one kind of traffic, not a detection result: no attack traffic is
involved and the traffic is not labelled (it is presumed benign because it was generated by ordinary browsing/downloading/lookups; whatever else
the computer sent in the same minutes is included). Only counts are written, never addresses.
Capture tip (headers only, 70 seconds, Wi-Fi interface number 4 of `dumpcap -D`):
  dumpcap -i 4 -s 96 -F pcap -a duration:70 -w ordinary.pcap
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.capture import FlowTable, packet_fields  # noqa: E402
from app.service import Detector  # noqa: E402


def flows_of(pcap: Path):
    from scapy.utils import PcapReader
    t, out, n = FlowTable(), [], 0
    with PcapReader(str(pcap)) as rd:
        for pkt in rd:
            n += 1
            f = packet_fields(pkt)
            if f is not None:
                s, d, sp, dp, pr, pl, hl, fl, w = f
                out += t.packet(s, d, sp, dp, pr, int(pkt.time * 1_000_000), pl, hl, fl, w)
    out += t.flush()
    return out, n, t.single_packet_flows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pcaps", nargs="+")
    ap.add_argument("--json")
    a = ap.parse_args()
    det = Detector()
    per_file, all_alerts, all_ood = [], {}, []
    for p in a.pcaps:
        flows, n_pkts, single = flows_of(Path(p))
        feats = [f for f, _ in flows]
        raw, proto = det.rows_to_arrays(feats)
        z = det.transform(raw, proto)
        out = det.score(z)
        ood = det.out_of_range(z)
        row = {"file": Path(p).name, "packets": n_pkts, "flows": len(feats), "single_packet_flows_not_reported": single,
               "flagged": {k: int(v.sum()) for k, v in out["alerts"].items()}, "flows_with_out_of_range_feature": int((ood > 0).sum()),
               "protocol_mix": {str(k): int(v) for k, v in zip(*np.unique(proto, return_counts=True))}}
        per_file.append(row)
        for k, v in out["alerts"].items():
            all_alerts[k] = all_alerts.get(k, 0) + int(v.sum())
        all_ood.append(ood)
    n = sum(r["flows"] for r in per_file)
    ood = np.concatenate(all_ood)
    total = {"flows": n, "flagged": all_alerts, "flagged_share": {k: v / n for k, v in all_alerts.items()},
             "flows_with_out_of_range_feature": int((ood > 0).sum()), "share_with_out_of_range_feature": float((ood > 0).mean())}
    res = {"per_file": per_file, "total": total,
           "thresholds": {k: det.thresholds[k] for k in det.thresholds},
           "note": "presumed-benign ordinary traffic; counts of flagged flows are false-alarm counts only if the flow really is benign"}
    for r in per_file:
        print(r["file"], r["packets"], "packets,", r["flows"], "flows; flagged:", r["flagged"], "; out-of-range flows:", r["flows_with_out_of_range_feature"])
    print("TOTAL", n, "flows; share flagged:", {k: round(v, 4) for k, v in total["flagged_share"].items()}, "; out-of-range share:", round(total["share_with_out_of_range_feature"], 4))
    if a.json:
        Path(a.json).write_text(json.dumps(res, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
